/**
 * RMS HTTP API (CRUD, NIBRS classify, push, pre-call context).
 *
 * GET    /api/rms/reports
 * GET    /api/rms/reports/{reportId}
 * PATCH  /api/rms/reports/{reportId}
 * POST   /api/rms/reports/{reportId}/finalize
 * GET    /api/rms/reports/{reportId}/export
 * POST   /api/rms/reports/{reportId}/push
 * POST   /api/rms/nibrs/classify
 * GET    /api/rms/context
 */

