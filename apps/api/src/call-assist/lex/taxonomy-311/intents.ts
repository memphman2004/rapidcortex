/**
 * Call Assist — 311 Non-Emergency Intent Registry
 *
 * 22 primary category intents + FallbackIntent.
 * Each intent uses:
 *   1. SubIssueType slot  — category-specific custom type for disambiguation
 *   2. ServiceAddress     — AMAZON.FreeFormInput (Lex V2 has no AMAZON.Address)
 *   3. IsOngoing          — CA_IsOngoing custom type
 *   4. IssueDescription   — freeform text capture
 *   5. CallerName         — AMAZON.FirstName (optional)
 *   6. CallbackNumber     — AMAZON.PhoneNumber (optional)
 *
 * Dialog Lambda handles:
 *   - Safety escalation keyword detection
 *   - Conditional sub-issue disambiguation
 *   - Address validation prompting
 *   - Department routing override based on sub-issue
 */

