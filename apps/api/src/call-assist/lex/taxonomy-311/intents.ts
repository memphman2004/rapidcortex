function mergeUtterances(base: string[], extra: string[] | undefined): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const u of [...base, ...(extra ?? [])]) {
    const key = u.trim().toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(u.trim());
  }
  return out;
}

