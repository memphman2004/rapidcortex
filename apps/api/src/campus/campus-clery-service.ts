function buildMatrix(entries: CleryEntry[]): CleryAsrCell[] {
  const map = new Map<string, CleryAsrCell>();
  for (const e of entries) {
    if (!e.includedInAsr) continue;
    const key = `${e.category}||${e.geography}`;
    const cell = map.get(key) ?? {
      category: e.category,
      geography: e.geography,
      count: 0,
      unfounded: 0,
    };
    if (e.unfounded) cell.unfounded += 1;
    else cell.count += 1;
    map.set(key, cell);
  }
  return [...map.values()].sort((a, b) =>
    a.category === b.category
      ? a.geography.localeCompare(b.geography)
      : a.category.localeCompare(b.category),
  );
}

