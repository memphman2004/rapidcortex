async function listAllPlatformIncidents(campusCode: string): Promise<CampusIncident[]> {
  const items: CampusIncident[] = [];
  let exclusiveStartKey: Record<string, unknown> | undefined;

  do {
    const result = await ddb.send(
      new QueryCommand({
        TableName: campusIncidentsTable(),
        KeyConditionExpression: "pk = :pk AND begins_with(sk, :sk)",
        ExpressionAttributeValues: {
          ":pk": CAMPUS_KEYS.incidentPk(campusCode),
          ":sk": "INCIDENT#",
        },
        ExclusiveStartKey: exclusiveStartKey,
      }),
    );
    for (const item of result.Items ?? []) {
      items.push(item as CampusIncident);
    }
    exclusiveStartKey = result.LastEvaluatedKey as Record<string, unknown> | undefined;
  } while (exclusiveStartKey);

  return items;
}

export async function syncCleryFromPlatform(opts: {
  agencyId: string;
  campusCode: string;
  academicYear: string;
  defaultGeography: CleryGeography;
  actorId: string;
}): Promise<{ created: number; skipped: number; entries: CleryEntry[] }> {
  if (!env.enableCampusClery) throw new Error("FEATURE_DISABLED");
  const { start, end } = academicYearBounds(opts.academicYear);
  const startMs = Date.parse(start);
  const endMs = Date.parse(end);

  const existing = await listCleryEntries(opts);
  const linked = new Set(
    existing.map((e) => e.platformIncidentId).filter(Boolean) as string[],
  );

  const incidents = await listAllPlatformIncidents(opts.campusCode);
  let created = 0;
  let skipped = 0;
  const entries: CleryEntry[] = [];

  for (const incident of incidents) {
    if (!incident.cleryCategory) {
      skipped += 1;
      continue;
    }
    const parsed = cleryCategorySchema.safeParse(incident.cleryCategory);
    if (!parsed.success) {
      skipped += 1;
      continue;
    }
    const occurredMs = Date.parse(incident.createdAt);
    if (Number.isNaN(occurredMs) || occurredMs < startMs || occurredMs > endMs) {
      skipped += 1;
      continue;
    }
    if (linked.has(incident.id)) {
      skipped += 1;
      continue;
    }

    const now = new Date().toISOString();
    const entryId = makeId("clery");
    const entry: CleryEntry = {
      entryId,
      agencyId: opts.agencyId,
      campusCode: opts.campusCode.toUpperCase(),
      academicYear: opts.academicYear,
      category: parsed.data,
      geography: (incident.cleryGeography as CleryGeography | null | undefined) ?? opts.defaultGeography,
      occurredAt: incident.createdAt,
      location: [incident.buildingLabel, incident.roomCode].filter(Boolean).join(", "),
      building: incident.buildingLabel,
      notes: incident.description.slice(0, 4000),
      hateCrimeBias: null,
      unfounded: false,
      includedInAsr: true,
      source: "platform_incident",
      externalSourceSystem: null,
      externalRecordId: null,
      platformIncidentId: incident.id,
      reviewedBy: null,
      reviewedAt: null,
      createdBy: opts.actorId,
      createdAt: now,
      updatedAt: now,
    };

    await putCleryEntry(entry, opts.actorId, AUDIT_EVENT_TYPES.CAMPUS_CLERY_PLATFORM_SYNCED);
    linked.add(incident.id);
    entries.push(entry);
    created += 1;
  }

  return { created, skipped, entries };
}

/** Parse a simple CSV (header row required) into Clery import rows. */
export function parseCleryCsv(csvText: string): CleryImportRow[] {
  const lines = csvText
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
  if (lines.length < 2) return [];

  const headers = splitCsvLine(lines[0]).map((h) => h.trim().toLowerCase());
  const required = ["occurredat", "category"];
  for (const r of required) {
    if (!headers.includes(r)) {
      throw new Error(`CSV_MISSING_COLUMN:${r}`);
    }
  }

  const rows: CleryImportRow[] = [];
  for (const line of lines.slice(1)) {
    const cols = splitCsvLine(line);
    const get = (name: string) => {
      const idx = headers.indexOf(name);
      return idx >= 0 ? (cols[idx] ?? "").trim() : "";
    };

    const categoryParsed = cleryCategorySchema.safeParse(get("category"));
    if (!categoryParsed.success) {
      throw new Error(`CSV_INVALID_CATEGORY:${get("category")}`);
    }

    const geoRaw = get("geography") || "on_campus";
    const geography = (CLERY_GEOGRAPHIES as readonly string[]).includes(geoRaw)
      ? (geoRaw as CleryGeography)
      : geoLabelToCode(geoRaw);

    rows.push({
      occurredAt: get("occurredat"),
      category: categoryParsed.data,
      geography,
      location: get("location"),
      building: get("building"),
      notes: get("notes"),
      hateCrimeBias: get("hatecrimebias") || null,
      unfounded: ["1", "true", "yes", "y"].includes(get("unfounded").toLowerCase()),
      includedInAsr: !["0", "false", "no", "n"].includes(get("includedinasr").toLowerCase()),
      externalRecordId: get("externalrecordid") || null,
    });
  }
  return rows;
}

function geoLabelToCode(label: string): CleryGeography {
  const lower = label.toLowerCase();
  for (const [code, pretty] of Object.entries(CLERY_GEOGRAPHY_LABELS) as Array<
    [CleryGeography, string]
  >) {
    if (pretty.toLowerCase() === lower || code === lower) return code;
  }
  return "on_campus";
}

function splitCsvLine(line: string): string[] {
  const out: string[] = [];
  let cur = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') {
        cur += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (ch === "," && !inQuotes) {
      out.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  out.push(cur);
  return out;
}
