export async function updateCleryEntry(
  campusCode: string,
  academicYear: string,
  entryId: string,
  agencyId: string,
  actorId: string,
  update: CleryEntryUpdateInput,
): Promise<CleryEntry> {
  if (!env.enableCampusClery) throw new Error("FEATURE_DISABLED");
  const existing = await getCleryEntry(campusCode, academicYear, entryId, agencyId);
  if (!existing) throw new Error("NOT_FOUND");

  const now = new Date().toISOString();
  const names: string[] = ["#updatedAt"];
  const values: Record<string, unknown> = { ":updatedAt": now };
  const sets: string[] = ["#updatedAt = :updatedAt"];

  const assign = (field: string, value: unknown, attr = field) => {
    names.push(`#${attr}`);
    values[`:${attr}`] = value;
    sets.push(`#${attr} = :${attr}`);
  };

  if (update.category !== undefined) assign("category", update.category);
  if (update.geography !== undefined) assign("geography", update.geography);
  if (update.occurredAt !== undefined) {
    assign("occurredAt", new Date(update.occurredAt).toISOString());
  }
  if (update.location !== undefined) assign("location", update.location);
  if (update.building !== undefined) assign("building", update.building);
  if (update.notes !== undefined) assign("notes", update.notes);
  if (update.hateCrimeBias !== undefined) assign("hateCrimeBias", update.hateCrimeBias);
  if (update.unfounded !== undefined) assign("unfounded", update.unfounded);
  if (update.includedInAsr !== undefined) assign("includedInAsr", update.includedInAsr);
  if (update.reviewed === true) {
    assign("reviewedBy", actorId);
    assign("reviewedAt", now);
  }

  const expressionNames = Object.fromEntries(
    names.map((n) => [n, n.replace("#", "")]),
  );

  await ddb.send(
    new UpdateCommand({
      TableName: campusIncidentsTable(),
      Key: {
        pk: CAMPUS_KEYS.incidentPk(campusCode),
        sk: CAMPUS_KEYS.cleryEntrySk(academicYear, entryId),
      },
      UpdateExpression: `SET ${sets.join(", ")}`,
      ExpressionAttributeNames: expressionNames,
      ExpressionAttributeValues: {
        ...values,
        ":agencyId": agencyId,
      },
      ConditionExpression: "agencyId = :agencyId",
    }),
  );

  const updated = await getCleryEntry(campusCode, academicYear, entryId, agencyId);
  if (!updated) throw new Error("NOT_FOUND");

  await auditRepo.create({
    eventId: makeId("audit"),
    agencyId,
    incidentId: updated.platformIncidentId ?? entryId,
    actorId,
    type: AUDIT_EVENT_TYPES.CAMPUS_CLERY_ENTRY_UPDATED,
    details: { campusCode, academicYear, entryId, fields: Object.keys(update) },
    createdAt: now,
    resourceType: "clery_entry",
    resourceId: entryId,
  });

  return updated;
}

